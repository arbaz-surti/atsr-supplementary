#!/usr/bin/env python3
"""Generate the evidence-bearing Results figures for the revised manuscript (step 5).

Reads the hash-locked operative analysis (`analysis-results.json`) and the step-4
cross-check file (`results-checks.json`) read-only, and writes standalone pgfplots
sources into `submission/figures/`:

  fig2-perspec-means.tex   specification-level condition means (Naive / GSQ / ATSR)
  fig3-atsr-gsq-forest.tex ATSR - GSQ estimate with bootstrap 95% CI across the
                           primary, missing-data sensitivity, rater-specific, model-
                           specific, and author-sensitivity analyses

Every plotted value is copied from those two files; nothing is recomputed here. A
sidecar `figure-data.json` records the plotted values and the SHA-256 of both inputs
so the figures can be traced and regenerated. Pass `--render` to compile the sources
to PDF with tectonic (the manuscript includes the PDFs).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LOCKED = ROOT / "revision_analysis" / "ATSR-SREP-R2-v1.0-operative-ratings-2026-09-18"
CHECKS = ROOT / "revision_analysis" / "ATSR-SREP-R2-v1.0-operative-ratings-2026-09-18-results-checks"
ANALYSIS = LOCKED / "analysis-results.json"
RESULTS_CHECKS = CHECKS / "results-checks.json"
FIG_DIR = ROOT.parent / "submission" / "figures"

# Grayscale only: the journal's print form must stay legible without colour.
INK = "black"
MID = "black!55"
RULE = "black!25"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fmt_signed(value: float) -> str:
    return f"{value:+.2f}"


# --------------------------------------------------------------------------- fig 2
def fig2_source(per_spec: list[dict]) -> tuple[str, list[dict]]:
    """Dumbbell plot: one row per specification, three condition markers, sorted by
    the ATSR - GSQ difference (largest at the top) so the paired pattern is visible."""
    rows = sorted(per_spec, key=lambda r: (r["atsr_minus_gsq"], r["spec_id"]), reverse=True)
    n = len(rows)
    ylabels = ",".join(f"{{{r['spec_id']}}}" for r in reversed(rows))
    # y = 1 at the bottom, n at the top
    segs, naive, gsq, atsr = [], [], [], []
    plotted = []
    for i, r in enumerate(rows):
        y = n - i
        lo = min(r["naive"], r["generic_structured_qa"], r["atsr"])
        hi = max(r["naive"], r["generic_structured_qa"], r["atsr"])
        segs.append(f"      \\draw[{RULE}, line width=1.6pt] (axis cs:{lo:.6f},{y}) -- (axis cs:{hi:.6f},{y});")
        naive.append(f"({r['naive']:.6f},{y})")
        gsq.append(f"({r['generic_structured_qa']:.6f},{y})")
        atsr.append(f"({r['atsr']:.6f},{y})")
        plotted.append({"spec_id": r["spec_id"], "row": y, "naive": r["naive"],
                        "generic_structured_qa": r["generic_structured_qa"], "atsr": r["atsr"],
                        "atsr_minus_gsq": r["atsr_minus_gsq"]})
    src = f"""%% Standalone source for Figure 2 -- specification-level condition means.
%% GENERATED by research/generate_revision_figures.py from the operative analysis
%% (results-checks.json, validated against analysis-results.json). Do not hand-edit;
%% re-run the script. Compile with tectonic/pdflatex -> fig2-perspec-means.pdf.
\\documentclass[border=4pt]{{standalone}}
\\usepackage{{pgfplots}}
\\pgfplotsset{{compat=1.18}}
\\begin{{document}}
  \\begin{{tikzpicture}}
    \\begin{{axis}}[
      width=12.4cm,
      height=11.2cm,
      xmin=12, xmax=24,
      xtick={{12,14,...,24}},
      xlabel={{Practitioner-averaged total score (5--25), mean over contributing models}},
      xlabel style={{font=\\small}},
      xticklabel style={{font=\\small}},
      ymin=0.4, ymax={n}.6,
      ytick={{1,...,{n}}},
      yticklabels={{{ylabels}}},
      yticklabel style={{font=\\small}},
      y dir=normal,
      xmajorgrids=true,
      grid style={{{RULE}, line width=0.4pt}},
      tick align=outside,
      axis line style={{{MID}}},
      axis x line*=bottom,
      axis y line*=left,
      legend style={{
        at={{(0.02,0.02)}},
        anchor=south west,
        font=\\small,
        draw={RULE},
        fill=white,
        legend columns=1,
      }},
      legend cell align=left,
      clip=false,
    ]
{chr(10).join(segs)}
      %% Naive: open circle
      \\addplot[only marks, mark=*, mark size=3pt, mark options={{fill=white, draw={INK}, line width=0.8pt}}]
        coordinates {{ {' '.join(naive)} }};
      \\addlegendentry{{Na\\"ive}}
      %% GSQ: mid-gray square
      \\addplot[only marks, mark=square*, mark size=2.7pt, mark options={{fill={MID}, draw={MID}}}]
        coordinates {{ {' '.join(gsq)} }};
      \\addlegendentry{{GSQ}}
      %% ATSR: filled black circle
      \\addplot[only marks, mark=*, mark size=3pt, mark options={{fill={INK}, draw={INK}}}]
        coordinates {{ {' '.join(atsr)} }};
      \\addlegendentry{{ATSR}}
    \\end{{axis}}
  \\end{{tikzpicture}}
\\end{{document}}
"""
    return src, plotted


# --------------------------------------------------------------------------- fig 3
def contrast_row(label: str, c: dict, group: str, marker: str = "filled") -> dict:
    lo, hi = c["bootstrap_95_ci_mean_difference"]
    return {
        "label": label,
        "group": group,
        "n": c["n_specifications"],
        "mean": c["paired_mean_difference"],
        "ci": [lo, hi],
        "p": c["wilcoxon_p_value"],
        "ptn": c["positive_ties_negative"],
        "marker": marker,
    }


def collect_forest_rows(analysis: dict) -> list[dict]:
    def pick(records: list[dict], model_label: str | None = None) -> dict:
        for r in records:
            if r["contrast"] == "ATSR - GSQ" and (model_label is None or r.get("model_label") == model_label):
                return r
        raise KeyError("ATSR - GSQ contrast not found")

    sens = analysis["missingness_sensitivities"]
    rows = [
        contrast_row("Primary: all available models", pick(analysis["primary_and_overall_contrasts"]), "Primary"),
        contrast_row("(i) Models valid under both conditions", pick(sens["common_models_within_each_specification_pair"]), "Missing-data sensitivity"),
        contrast_row("(ii) GPT-4o and Llama 3.3 70B only", pick(sens["complete_GPT4o_and_Llama_models_only"]), "Missing-data sensitivity"),
        contrast_row("(iii) All three models valid in both", pick(sens["fully_observed_three_model_specification_pairs"]), "Missing-data sensitivity"),
        contrast_row("Practitioner 01 only", pick(analysis["rater_specific_contrasts"]["PRACTITIONER-01"]), "By rater"),
        contrast_row("Practitioner 02 only", pick(analysis["rater_specific_contrasts"]["PRACTITIONER-02"]), "By rater"),
        contrast_row("GPT-4o", pick(analysis["model_specific_contrasts"], "GPT-4o"), "By model family"),
        contrast_row("Claude Sonnet 4.6", pick(analysis["model_specific_contrasts"], "Claude Sonnet 4.6"), "By model family"),
        contrast_row("Llama 3.3 70B", pick(analysis["model_specific_contrasts"], "Llama 3.3 70B"), "By model family"),
        contrast_row("Author ratings (sensitivity)", pick(analysis["author_anchor_contrasts"]), "Author", marker="open"),
    ]
    return rows


def fig3_source(rows: list[dict]) -> str:
    n = len(rows)
    ylabels = ",".join(f"{{{r['label']}}}" for r in reversed(rows))
    filled, open_, errs, texts, seps = [], [], [], [], []
    prev_group = None
    for i, r in enumerate(rows):
        y = n - i
        lo, hi = r["ci"]
        m = r["mean"]
        errs.append(f"({m:.6f},{y}) -= ({m - lo:.6f},0) += ({hi - m:.6f},0)")
        (filled if r["marker"] == "filled" else open_).append(f"({m:.6f},{y})")
        ptn = r["ptn"]
        texts.append(
            f"      \\node[anchor=west, xshift=3mm, font=\\small] at (axis cs:6.2,{y}) "
            f"{{${fmt_signed(m)}$ [{fmt_signed(lo)}, {fmt_signed(hi)}]}};"
        )
        texts.append(
            f"      \\node[anchor=west, xshift=42mm, font=\\small] at (axis cs:6.2,{y}) "
            f"{{{r['n']}}};"
        )
        texts.append(
            f"      \\node[anchor=west, xshift=50mm, font=\\small] at (axis cs:6.2,{y}) "
            f"{{{ptn['positive']}/{ptn['ties']}/{ptn['negative']}}};"
        )
        if prev_group is not None and r["group"] != prev_group:
            seps.append(f"      \\draw[{MID}, line width=0.4pt] (axis cs:-1.6,{y + 0.5}) -- ([xshift=66mm]axis cs:6.2,{y + 0.5});")
        prev_group = r["group"]
    # group labels in the left margin are carried by the tick labels; add column headers
    headers = (
        f"      \\node[anchor=west, xshift=3mm, font=\\small\\bfseries] at (axis cs:6.2,{n + 0.95}) {{Mean $\\Delta$ [95\\% CI]}};\n"
        f"      \\node[anchor=west, xshift=42mm, font=\\small\\bfseries] at (axis cs:6.2,{n + 0.95}) {{$n$}};\n"
        f"      \\node[anchor=west, xshift=50mm, font=\\small\\bfseries] at (axis cs:6.2,{n + 0.95}) {{$+$/$=$/$-$}};"
    )
    src = f"""%% Standalone source for Figure 3 -- ATSR - GSQ estimates across analyses.
%% GENERATED by research/generate_revision_figures.py from the operative analysis
%% (analysis-results.json). Do not hand-edit; re-run the script.
%% Compile with tectonic/pdflatex -> fig3-atsr-gsq-forest.pdf.
\\documentclass[border=4pt]{{standalone}}
\\usepackage{{pgfplots}}
\\pgfplotsset{{compat=1.18}}
\\begin{{document}}
  \\begin{{tikzpicture}}
    \\begin{{axis}}[
      width=8.0cm,
      height=9.0cm,
      xmin=-1.6, xmax=6.2,
      xtick={{-1,0,1,2,3,4,5,6}},
      xlabel={{ATSR $-$ GSQ paired mean difference, total score (points)}},
      xlabel style={{font=\\small}},
      xticklabel style={{font=\\small}},
      ymin=0.4, ymax={n}.6,
      ytick={{1,...,{n}}},
      yticklabels={{{ylabels}}},
      yticklabel style={{font=\\small, align=right}},
      xmajorgrids=true,
      grid style={{{RULE}, line width=0.4pt}},
      tick align=outside,
      axis line style={{{MID}}},
      axis x line*=bottom,
      axis y line*=left,
      clip=false,
    ]
      %% zero reference (solid hairline, slightly darker than the grid)
      \\draw[{MID}, line width=0.6pt] (axis cs:0,0.4) -- (axis cs:0,{n}.6);
{chr(10).join(seps)}
      \\addplot[only marks, mark=none, error bars/.cd, x dir=both, x explicit,
               error bar style={{{INK}, line width=0.9pt}}, error mark options={{rotate=90, mark size=2pt, {INK}}}]
        coordinates {{ {' '.join(errs)} }};
      \\addplot[only marks, mark=*, mark size=2.6pt, mark options={{fill={INK}, draw={INK}}}]
        coordinates {{ {' '.join(filled)} }};
      \\addplot[only marks, mark=*, mark size=2.6pt, mark options={{fill=white, draw={INK}, line width=0.8pt}}]
        coordinates {{ {' '.join(open_)} }};
{headers}
{chr(10).join(texts)}
    \\end{{axis}}
  \\end{{tikzpicture}}
\\end{{document}}
"""
    return src


# --------------------------------------------------------------------------- main
def render(tex: Path) -> None:
    subprocess.run(["tectonic", "--keep-logs", "-o", str(tex.parent), str(tex)], check=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--render", action="store_true", help="compile the sources to PDF with tectonic")
    args = parser.parse_args()

    analysis = json.loads(ANALYSIS.read_text())
    checks = json.loads(RESULTS_CHECKS.read_text())
    if checks["input_hashes"]["analysis-results.json"] != sha256(ANALYSIS):
        raise SystemExit("results-checks.json was built from a different analysis-results.json")
    validation = checks["per_specification_validation_against_locked_differences"]
    if not all(v is True for v in validation.values()):
        raise SystemExit(f"per-specification means do not reproduce the locked differences: {validation}")

    per_spec = checks["per_specification_condition_means"]
    fig2, fig2_rows = fig2_source(per_spec)
    forest_rows = collect_forest_rows(analysis)
    fig3 = fig3_source(forest_rows)

    FIG_DIR.mkdir(parents=True, exist_ok=True)
    (FIG_DIR / "fig2-perspec-means.tex").write_text(fig2)
    (FIG_DIR / "fig3-atsr-gsq-forest.tex").write_text(fig3)
    sidecar = {
        "generator": "research/generate_revision_figures.py",
        "protocol_id": analysis["protocol_id"],
        "input_hashes": {
            "analysis-results.json": sha256(ANALYSIS),
            "results-checks.json": sha256(RESULTS_CHECKS),
        },
        "fig2_perspec_means": {"sort": "atsr_minus_gsq descending", "rows": fig2_rows},
        "fig3_atsr_gsq_forest": {"rows": forest_rows},
    }
    (FIG_DIR / "figure-data.json").write_text(json.dumps(sidecar, indent=2) + "\n")
    print("wrote", FIG_DIR / "fig2-perspec-means.tex")
    print("wrote", FIG_DIR / "fig3-atsr-gsq-forest.tex")
    print("wrote", FIG_DIR / "figure-data.json")
    if args.render:
        for name in ("fig2-perspec-means.tex", "fig3-atsr-gsq-forest.tex"):
            render(FIG_DIR / name)
            print("rendered", (FIG_DIR / name).with_suffix(".pdf"))


if __name__ == "__main__":
    main()
